"use client";

import { useRef, useState } from "react";
import { Download, ImagePlus, LoaderCircle, ShieldCheck, Sparkles, Upload, X } from "lucide-react";
import { removeWatermarkFromImage } from "@pilio/gemini-watermark-remover";

const MAX_FILE_SIZE = 20 * 1024 * 1024;

export default function GeminiImageRemover() {
  const inputRef = useRef(null);
  const [source, setSource] = useState(null);
  const [result, setResult] = useState(null);
  const [fileName, setFileName] = useState("");
  const [status, setStatus] = useState("idle");
  const [message, setMessage] = useState("");
  const [details, setDetails] = useState("");

  function clearCurrent() {
    if (source?.url) URL.revokeObjectURL(source.url);
    if (result?.url) URL.revokeObjectURL(result.url);
    setSource(null);
    setResult(null);
    setFileName("");
    setStatus("idle");
    setMessage("");
    setDetails("");
    if (inputRef.current) inputRef.current.value = "";
  }

  function acceptFile(file) {
    if (!file) return;
    if (!["image/png", "image/jpeg", "image/webp"].includes(file.type)) {
      setMessage("Please select a PNG, JPG, or WebP image.");
      if (inputRef.current) inputRef.current.value = "";
      return;
    }
    if (file.size > MAX_FILE_SIZE) {
      setMessage("This image is larger than 20 MB. Please choose a smaller image.");
      return;
    }
    clearCurrent();
    const url = URL.createObjectURL(file);
    setSource({ file, url });
    setFileName(file.name.replace(/\.[^.]+$/, "") || "gemini-image");
    setMessage("");
    setStatus("ready");
  }

  async function processImage() {
    if (!source?.file || status === "processing") return;
    setStatus("processing");
    setMessage("");
    setDetails("");
    let resultUrl;
    try {
      const image = new window.Image();
      image.decoding = "async";
      image.src = source.url;
      await image.decode();
      const processed = await removeWatermarkFromImage(image);
      if (!processed?.canvas || typeof processed.canvas.toBlob !== "function") {
        throw new Error("The image engine did not return a processed image.");
      }
      const blob = await new Promise((resolve, reject) => {
        processed.canvas.toBlob((value) => value ? resolve(value) : reject(new Error("Could not prepare the processed image for download.")), "image/png");
      });
      resultUrl = URL.createObjectURL(blob);
      setResult({ url: resultUrl, blob, width: processed.canvas.width, height: processed.canvas.height });
      const applied = processed.meta?.applied;
      setStatus("done");
      if (applied === false) {
        setMessage("No supported Gemini watermark was confidently detected. The output may look the same as the original.");
      } else {
        setMessage("Processing finished. Review the result before downloading or publishing it.");
      }
      if (processed.meta?.decisionTier) setDetails(`Detection result: ${processed.meta.decisionTier}`);
    } catch (error) {
      if (resultUrl) URL.revokeObjectURL(resultUrl);
      setStatus("error");
      setMessage(error?.message || "This image could not be processed. Try an original Gemini image in PNG or JPG format.");
    }
  }

  function downloadResult() {
    if (!result?.url) return;
    const anchor = document.createElement("a");
    anchor.href = result.url;
    anchor.download = `${fileName || "gemini-image"}-processed.png`;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
  }

  return (
    <section className="remover-tool" aria-labelledby="remover-tool-title">
      <div className="remover-heading">
        <span className="remover-eyebrow"><Sparkles size={15} /> FREE BROWSER TOOL</span>
        <h2 id="remover-tool-title">Process a Gemini image</h2>
        <p>Select an image generated by Gemini. Processing runs in your browser; the image is not sent to Promptzyra servers by this tool.</p>
      </div>

      {!source ? (
        <button type="button" className="remover-dropzone" onClick={() => inputRef.current?.click()} onDragOver={(event) => event.preventDefault()} onDrop={(event) => { event.preventDefault(); acceptFile(event.dataTransfer.files?.[0]); }}>
          <span className="remover-upload-icon"><ImagePlus size={26} /></span>
          <strong>Drop your image here</strong>
          <span>or choose a file from your device</span>
          <small>PNG, JPG, WebP · Up to 20 MB</small>
          <span className="remover-choose"><Upload size={16} /> Choose image</span>
        </button>
      ) : (
        <div className="remover-workspace">
          <div className="remover-preview-grid">
            <figure><figcaption>Original image</figcaption><div className="remover-image-frame"><img src={source.url} alt="Original image selected for processing" /></div></figure>
            <figure><figcaption>Processed preview</figcaption><div className="remover-image-frame">{result ? <img src={result.url} alt="Processed image preview" /> : <div className="remover-placeholder"><Sparkles size={24} /><span>{status === "processing" ? "Processing image…" : "Your result will appear here"}</span></div>}</div></figure>
          </div>
          <div className="remover-fileline"><span>{source.file.name} · {(source.file.size / (1024 * 1024)).toFixed(2)} MB</span><button type="button" className="remover-reset" onClick={clearCurrent}><X size={15} /> Remove image</button></div>
          <div className="remover-actions">
            <button type="button" className="remover-primary" onClick={processImage} disabled={status === "processing"}>{status === "processing" ? <><LoaderCircle className="remover-spin" size={17} /> Processing…</> : <><Sparkles size={17} /> Process image</>}</button>
            {result && <button type="button" className="remover-secondary" onClick={downloadResult}><Download size={17} /> Download PNG</button>}
          </div>
        </div>
      )}

      {message && <p className={`remover-message ${status === "error" ? "is-error" : ""}`} role="status">{message}</p>}
      {details && <p className="remover-details">{details}</p>}
      <p className="remover-privacy"><ShieldCheck size={16} /> Local processing · No account required · Original file stays on your device</p>
      <input ref={inputRef} className="visually-hidden-input" type="file" accept="image/png,image/jpeg,image/webp,image/*" onChange={(event) => acceptFile(event.target.files?.[0])} />
    </section>
  );
}
